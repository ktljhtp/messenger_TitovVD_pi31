#pragma once

#include "../common/message.h"

// ──────────────────────────────────────────
//  Публичный интерфейс UI
// ──────────────────────────────────────────

// Инициализация — вызвать один раз после входа
// login — логин текущего пользователя (для заголовков)
void ui_init(const char *login);

// Вызывается из receiver_thread при получении сообщения
// Добавляет в нужный чат и показывает уведомление если чат не открыт
void ui_receive_message(const Message *msg);

// Главный цикл UI — блокирует поток пока пользователь не введёт /quit
// server_fd нужен для отправки сообщений
void ui_run(int server_fd);

// Завершить UI, восстановить терминал
void ui_cleanup();