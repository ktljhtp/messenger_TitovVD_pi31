#pragma once

#include "../common/message.h"

// ──────────────────────────────────────────
//  Модуль пользовательского интерфейса (ncurses)
//
//  Экран делится на два окна:
//    - chat_win  : 80% высоты — история переписки
//    - input_win : 20% высоты — строка ввода
//
//  Потокобезопасность: ui_print_message() и
//  ui_read_input() защищены внутренним мьютексом.
// ──────────────────────────────────────────

// Инициализировать ncurses, создать окна
// Вызывать один раз после успешной аутентификации
void ui_init();

// Вывести сообщение в окно чата
// Формат строки: [ЧЧ:ММ:СС] sender → receiver: текст
// Потокобезопасна — можно вызывать из receiver_thread
void ui_print_message(const Message *msg);

// Вывести системное уведомление (выделено цветом)
// Используется для сообщений типа "Пользователь не в сети"
void ui_print_system(const char *text);

// Прочитать строку ввода из нижнего окна
// Поддерживает: Backspace, стрелки ← →, Ctrl+C (возвращает -1)
// Возвращает длину строки или -1 при выходе
int ui_read_input(char *buf, int maxlen);

// Завершить работу ncurses, восстановить терминал
void ui_cleanup();
