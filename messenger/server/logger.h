#pragma once

// ──────────────────────────────────────────
//  Модуль логирования
//
//  Все события сервера (подключения, ошибки,
//  маршрутизация) пишутся в server.log
//  с временной меткой.
// ──────────────────────────────────────────

// Открыть лог-файл (вызвать один раз при старте сервера)
void log_open(const char *path);

// Закрыть лог-файл (вызвать перед завершением)
void log_close();

// Записать строку в лог — поддерживает форматирование как printf
// Пример: log_event("Клиент %s подключился с %s", login, ip);
void log_event(const char *format, ...);
